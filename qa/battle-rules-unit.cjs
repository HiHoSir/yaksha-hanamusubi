const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs');
const ctx={};ctx.window=ctx;vm.runInNewContext(fs.readFileSync('js/battle-rules.js','utf8'),ctx);
const r=ctx.YK_BATTLE_RULES;
assert.equal(r.allyDamage('attack',1,20,2,()=>0),22);
assert.equal(r.allyDamage('skill',3,20,2,()=>.999),42);
assert.equal(r.shellDamage(1),1);
assert.equal(r.shellDamage(20),7);
assert.equal(r.foeDamage(22,10,5,false,false,()=>0),17);
assert.equal(r.foeDamage(22,10,5,true,true,()=>0),12);
assert.equal(r.foeDamage(1,30,0,false,true,()=>0),1);
const party={hp:40,maxhp:100,mp:5,potions:2};
assert.equal(r.validateCommand('bloom',party).action,'skill');
assert.equal(r.validateCommand('bloom',party).cost,4);
assert.equal(r.validateCommand('heal',{...party,mp:2}).message,'技が足りない！');
assert.equal(r.validateCommand('herb',{...party,hp:100}).message,'体は満ちている。');
assert.equal(r.validateCommand('herb',{...party,potions:0}).message,'薬草を持っていない。');
assert.equal(r.validateCommand('herb',party).action,'item');
assert.equal(r.validateCommand('guard',party).cost,0);
console.log('Battle arithmetic and command rules contract OK');
