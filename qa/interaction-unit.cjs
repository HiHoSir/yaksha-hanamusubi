const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const c={};c.window=c;vm.runInNewContext(fs.readFileSync('js/interaction.js','utf8'),c);
const find=(p,ns,max)=>c.YK_INTERACTION.nearestFacingNPC(p,ns,max);
const p={x:0,y:0,dir:'u'},front={x:0,y:-10},back={x:0,y:10};
assert.equal(find(p,[back,front]),front);
assert.equal(find(p,[{x:0,y:-93}]),null);
assert.equal(find(p,[front],10),null);
assert.equal(find({...p,dir:'invalid'},[back]),back);
const side={x:10,y:0},diagonal={x:10,y:-10};
assert.equal(find(p,[side]),null,'side NPC must not trigger dialogue');
assert.equal(find(p,[diagonal]),null,'diagonal NPC outside facing cone');
assert.equal(find({...p,dir:'r'},[side]),side,'turning toward NPC should allow dialogue');
assert.equal(find({...p,dir:'d'},[front]),null,'NPC behind must not trigger dialogue');
assert.equal(find({...p,dir:'r'},[front,side]),side,'facing must win over unrelated nearby NPC');
assert.ok(find({...p,dir:'u'},[{x:3,y:-20}]),'slightly offset forward NPC should remain selectable');
console.log('NPC-facing selection contract OK');
