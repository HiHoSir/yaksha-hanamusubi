const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const M=require('../js/settlement-map/model'),K=require('../js/sanctuary-main-core');
const map=M.parse(fs.readFileSync('assets/settlement-editor/maps/tenyo-sanctuary-water-v5.json','utf8'));
const ctx={console,YK_TENYO:K.create(M,map)};ctx.window=ctx;
vm.runInNewContext(fs.readFileSync('js/area-transitions.js','utf8'),ctx);
const {exit,apply}=ctx.YK_AREA_TRANSITIONS;
const village={exit:{rect:[10,10,50,50],to:'field'},northExit:{rect:[100,100,200,200],to:'shrine'}};
const world={hub:[25,35],places:{shrine:{point:[71,81]},village:{point:[40,50]}}};
assert.equal(exit('village',20,20,village,world),'field');
assert.equal(exit('village',150,150,village,world),'shrine');
assert.equal(exit('village',10,20,village,world),null);
assert.equal(exit('village',100,150,village,world),'shrine');
assert.equal(exit('shrine',41,100,village,world),null,'old west exit must be disabled');
assert.equal(exit('shrine',432,784,village,world),'field','authored southern approach exits to field');
assert.equal(exit('shrine',432,752,village,world),null,'entry spawn stays in shrine');
assert.equal(exit('shrine',368,784,village,world),null,'rock left of south exit');
assert.equal(exit('shrine',528,784,village,world),null,'rock right of south exit');
assert.equal(exit('teahouse',5,5,village,world),null);
assert.equal(exit('villageRoom',5,5,village,world),null);
const state={area:'village',x:800,y:1200,dir:'u',visitedAreas:{village:true},frame:2,encounterSteps:7,encounterGrace:0};
apply(state,'field',world,{field:{grace:4}});
assert.equal(state.x,40);assert.equal(state.y,50);assert.equal(state.dir,'d');assert.equal(state.encounterGrace,4);
apply(state,'shrine',world,{shrine:{grace:8}});
assert.equal(state.x,70);assert.equal(state.y,430);assert.equal(state.visitedAreas.shrine,true);assert.equal(state.encounterSteps,0);
console.log('Area exits and transition state contracts OK');
