const assert=require("node:assert/strict");
const fs=require("node:fs"),vm=require("node:vm");
const context={};
vm.runInNewContext(fs.readFileSync("js/battle-party-adapter.js","utf8"),context);
const adapter=context.YK_BATTLE_PARTY_ADAPTER;
const source={name:"緋月",hp:35,maxhp:80,mp:8,maxmp:20,lv:4,atk:13,def:6};
const members=[{id:"a",name:"仲間",hp:50,maxhp:60,mp:3,maxmp:5},{id:"a",hp:10,maxhp:10},{id:"b",hp:0,maxhp:22},{id:"c",hp:7,maxhp:20},{id:"d",hp:9,maxhp:20}];
const party=adapter.fromGameState(source,members);
assert.equal(party.length,4);
assert.equal(party[0].name,"緋月");
assert.equal(party[0].level,4);
assert.equal(party[1].name,"仲間");
assert.equal(party[2].active,false);
assert.equal(party[3].id,"c");
party[0].hp=1;party[1].statuses.poison=true;
assert.equal(source.hp,35);
assert.equal(members[0].statuses,undefined);
const result=adapter.toResults(party);
assert.equal(result[0].hp,1);
const patch=adapter.leaderPatch(source,result);
assert.equal(patch.hp,1);
assert.equal(source.hp,35);
assert.equal(adapter.leaderPatch(source,[{id:"leader",hp:900,mp:-2}]).hp,80);
assert.equal(adapter.leaderPatch(source,[{id:"leader",hp:900,mp:-2}]).mp,0);
assert.throws(()=>adapter.leaderPatch(source,[]),/Leader result missing/);
assert.throws(()=>adapter.leaderPatch(source,[{id:"leader",hp:NaN,mp:0}]),/Invalid battle result/);
assert.equal(adapter.fromGameState({hp:5,maxhp:10}).length,1);
console.log("Battle party adapter OK");
